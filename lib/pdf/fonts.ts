/** Ancho del texto en puntos, incluido el espaciado entre letras. */
export function textWidth(text: string, font: PdfFontName, size: number, letterSpacing = 0) {
  const table = WIDTHS[font];
  let total = 0;
  for (let index = 0; index < text.length; index += 1) total += table[winAnsiCode(text.charCodeAt(index)) - FIRST_CODE] ?? 0;
  return (total / 1000) * size + Math.max(0, text.length - 1) * letterSpacing;
}
